"""
Regenerates the .designer.cs file for every .aspx / .Master in TreeRecycle.Web from its markup,
the way Visual Studio would. Run after editing markup:   python -I tools/gen_designers.py

Only controls with runat="server" and an ID, outside templated controls (Repeater etc.), get fields.
"""
import os
import re

ROOT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "TreeRecycle.Web")

TEMPLATED = {"asp:repeater", "asp:listview", "asp:gridview", "asp:datalist", "asp:formview", "asp:detailsview"}
SPECIAL = {
    "asp:contentplaceholder": "System.Web.UI.WebControls.ContentPlaceHolder",
    "asp:scriptmanager": "System.Web.UI.ScriptManager",
    "asp:updatepanel": "System.Web.UI.UpdatePanel",
}
HTML = {
    "form": "System.Web.UI.HtmlControls.HtmlForm",
    "head": "System.Web.UI.HtmlControls.HtmlHead",
    "a": "System.Web.UI.HtmlControls.HtmlAnchor",
}

TAG = re.compile(r"<(/?)([A-Za-z][\w:]*)([^>]*?)(/?)>", re.S)
ID = re.compile(r'\bID\s*=\s*"([^"]+)"', re.I)
RUNAT = re.compile(r'\brunat\s*=\s*"server"', re.I)
DIRECTIVE = re.compile(r"<%@\s*(Page|Master|Control)([^%]*)%>", re.I)
INHERITS = re.compile(r'Inherits\s*=\s*"([^"]+)"', re.I)


def fields_for(markup):
    stripped = re.sub(r"<%.*?%>", "", markup, flags=re.S)
    stripped = re.sub(r"<!--.*?-->", "", stripped, flags=re.S)
    fields, skip_depth, stack = [], 0, []
    for m in TAG.finditer(stripped):
        closing, name, attrs, selfclose = m.group(1), m.group(2).lower(), m.group(3), m.group(4)
        if closing:
            if stack and stack[-1] == name:
                stack.pop()
                if name in TEMPLATED and skip_depth:
                    skip_depth -= 1
            continue
        if skip_depth == 0 and RUNAT.search(attrs):
            idm = ID.search(attrs)
            if idm:
                if name in SPECIAL:
                    typ = SPECIAL[name]
                elif name.startswith("asp:"):
                    typ = "System.Web.UI.WebControls." + m.group(2).split(":")[1]
                else:
                    typ = HTML.get(name, "System.Web.UI.HtmlControls.HtmlGenericControl")
                if name != "asp:content":
                    fields.append((idm.group(1), typ))
        if not selfclose:
            stack.append(name)
            if name in TEMPLATED:
                skip_depth += 1
    return fields


def main():
    count = 0
    for folder, _, files in os.walk(ROOT):
        if os.sep + "bin" in folder or os.sep + "obj" in folder:
            continue
        for f in files:
            if not (f.endswith(".aspx") or f.endswith(".Master")):
                continue
            path = os.path.join(folder, f)
            markup = open(path, encoding="utf-8-sig").read()
            d = DIRECTIVE.search(markup)
            inh = INHERITS.search(d.group(2)) if d else None
            if not inh:
                continue
            full = inh.group(1)
            ns, cls = full.rsplit(".", 1)
            lines = ["//------------------------------------------------------------------------------",
                     "// <auto-generated>",
                     "//     Generated by tools/gen_designers.py from " + f + ". Do not edit by hand.",
                     "// </auto-generated>",
                     "//------------------------------------------------------------------------------",
                     "",
                     "namespace " + ns + " {",
                     "",
                     "    public partial class " + cls + " {"]
            for fid, typ in fields_for(markup):
                lines += ["", "        protected global::" + typ + " " + fid + ";"]
            lines += ["    }", "}", ""]
            with open(path + ".designer.cs", "w", encoding="utf-8", newline="\r\n") as out:
                out.write("\n".join(lines))
            count += 1
    print("Wrote %d designer files" % count)


if __name__ == "__main__":
    main()
